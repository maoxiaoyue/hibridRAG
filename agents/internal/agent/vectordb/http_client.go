// Package vectordb — http_client.go: delegates embed+store to agent_embedding service.
package vectordb

import (
	"bytes"
	"context"
	"crypto/tls"
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"time"

	"golang.org/x/net/http2"
)

// UpsertText is a text-only chunk forwarded to agent_embedding for embed+store.
// No embedding vector required — the agent_embedding service computes it.
type UpsertText struct {
	ChunkID string // optional; auto-generated by agent_embedding if empty
	Text    string
}

// HTTPClient delegates embed+store operations to the agent_embedding HTTP service.
// It wraps /api/upsert, /api/search, and DELETE /api/chunks.
type HTTPClient struct {
	baseURL string
	http    *http.Client
}

// NewHTTPClient creates an HTTPClient pointing to the agent_embedding service.
func NewHTTPClient(baseURL string, timeout time.Duration) *HTTPClient {
	if timeout <= 0 {
		timeout = 30 * time.Second
	}
	// agent_embedding runs HypGo's protocol: http2 with a self-signed dev cert
	// (see agent_embedding/scripts/gencert); skip verification like a2a_client does.
	t1 := &http.Transport{TLSClientConfig: &tls.Config{InsecureSkipVerify: true}} //nolint:gosec
	_ = http2.ConfigureTransport(t1)

	return &HTTPClient{
		baseURL: strings.TrimRight(baseURL, "/"),
		http:    &http.Client{Timeout: timeout, Transport: t1},
	}
}

// UpsertTexts sends text chunks to agent_embedding POST /api/upsert.
// agent_embedding handles BGE-M3 embedding and Cassandra storage.
func (c *HTTPClient) UpsertTexts(ctx context.Context, agentID, docID string, chunks []UpsertText) error {
	type item struct {
		ChunkID string `json:"chunk_id,omitempty"`
		Text    string `json:"text"`
	}
	type reqBody struct {
		AgentID string `json:"agent_id"`
		DocID   string `json:"doc_id"`
		Chunks  []item `json:"chunks"`
	}

	items := make([]item, len(chunks))
	for i, ch := range chunks {
		items[i] = item{ChunkID: ch.ChunkID, Text: ch.Text}
	}

	body, _ := json.Marshal(reqBody{AgentID: agentID, DocID: docID, Chunks: items})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.baseURL+"/api/upsert", bytes.NewReader(body))
	if err != nil {
		return fmt.Errorf("vectordb http upsert: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := c.http.Do(req)
	if err != nil {
		return fmt.Errorf("vectordb http upsert: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		var e struct {
			Error string `json:"error"`
		}
		json.NewDecoder(resp.Body).Decode(&e) //nolint:errcheck
		return fmt.Errorf("vectordb http upsert: HTTP %d: %s", resp.StatusCode, e.Error)
	}
	return nil
}

// httpSearchHit mirrors the agent_embedding SearchHit JSON response.
type httpSearchHit struct {
	ChunkID    string  `json:"chunk_id"`
	AgentID    string  `json:"agent_id"`
	DocID      string  `json:"doc_id"`
	Text       string  `json:"text"`
	Similarity float32 `json:"similarity"`
}

// SearchByQuery calls agent_embedding POST /api/search with a text query.
// Returns SearchHits ordered by cosine similarity (highest first).
func (c *HTTPClient) SearchByQuery(ctx context.Context, agentID, query string, topK int) ([]SearchHit, error) {
	type reqBody struct {
		AgentID string `json:"agent_id"`
		Query   string `json:"query"`
		TopK    int    `json:"top_k,omitempty"`
	}
	type respBody struct {
		Results []httpSearchHit `json:"results"`
		Total   int             `json:"total"`
	}

	body, _ := json.Marshal(reqBody{AgentID: agentID, Query: query, TopK: topK})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.baseURL+"/api/search", bytes.NewReader(body))
	if err != nil {
		return nil, fmt.Errorf("vectordb http search: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := c.http.Do(req)
	if err != nil {
		return nil, fmt.Errorf("vectordb http search: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		var e struct {
			Error string `json:"error"`
		}
		json.NewDecoder(resp.Body).Decode(&e) //nolint:errcheck
		return nil, fmt.Errorf("vectordb http search: HTTP %d: %s", resp.StatusCode, e.Error)
	}

	var result respBody
	if err := json.NewDecoder(resp.Body).Decode(&result); err != nil {
		return nil, fmt.Errorf("vectordb http search: decode: %w", err)
	}

	hits := make([]SearchHit, len(result.Results))
	for i, h := range result.Results {
		hits[i] = SearchHit{
			ChunkID:    h.ChunkID,
			AgentID:    h.AgentID,
			DocID:      h.DocID,
			Text:       h.Text,
			Similarity: h.Similarity,
		}
	}
	return hits, nil
}

// DeleteByDoc removes all chunks for (agent_id, doc_id) via DELETE /api/chunks.
func (c *HTTPClient) DeleteByDoc(ctx context.Context, agentID, docID string) (int, error) {
	url := fmt.Sprintf("%s/api/chunks?agent_id=%s&doc_id=%s", c.baseURL, agentID, docID)
	req, err := http.NewRequestWithContext(ctx, http.MethodDelete, url, nil)
	if err != nil {
		return 0, fmt.Errorf("vectordb http delete: %w", err)
	}

	resp, err := c.http.Do(req)
	if err != nil {
		return 0, fmt.Errorf("vectordb http delete: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		var e struct {
			Error string `json:"error"`
		}
		json.NewDecoder(resp.Body).Decode(&e) //nolint:errcheck
		return 0, fmt.Errorf("vectordb http delete: HTTP %d: %s", resp.StatusCode, e.Error)
	}

	var result struct {
		Deleted int `json:"deleted"`
	}
	json.NewDecoder(resp.Body).Decode(&result) //nolint:errcheck
	return result.Deleted, nil
}
